r"""
Dataset Splitter for YOLO Training
Randomly splits images and labels into train/valid/test sets

Usage:
    python split_dataset.py --source "C:\path\to\images" --output "dataset"
    python split_dataset.py --source "C:\path\to\images" --train 0.7 --valid 0.15 --test 0.15
"""

import argparse
import random
import shutil
from pathlib import Path
from typing import Tuple

def split_dataset(
    source_dir: str,
    output_dir: str = "dataset",
    train_ratio: float = 0.7,
    valid_ratio: float = 0.15,
    test_ratio: float = 0.15,
    seed: int = 42
):
    """
    Split images and labels into train/valid/test sets.
    
    Args:
        source_dir: Directory containing images (and optionally labels)
        output_dir: Output directory for split dataset
        train_ratio: Fraction for training set (default 0.7 = 70%)
        valid_ratio: Fraction for validation set (default 0.15 = 15%)
        test_ratio: Fraction for test set (default 0.15 = 15%)
        seed: Random seed for reproducibility
    """
    print("📊 YOLO Dataset Splitter")
    print("=" * 60)
    
    # Validate ratios
    if abs(train_ratio + valid_ratio + test_ratio - 1.0) > 0.001:
        raise ValueError(f"Ratios must sum to 1.0 (got {train_ratio + valid_ratio + test_ratio})")
    
    # Setup paths
    source_path = Path(source_dir)
    output_path = Path(output_dir)
    
    # Find all images
    image_extensions = ['.jpg', '.jpeg', '.png', '.bmp']
    images = [f for f in source_path.glob('*') if f.suffix.lower() in image_extensions]
    
    if not images:
        print(f"❌ No images found in {source_dir}")
        return
    
    print(f"📸 Found {len(images)} images")
    
    # Check for labels directory
    labels_dir = source_path / 'labels'
    has_labels = labels_dir.exists()
    
    if has_labels:
        print(f"📝 Labels directory found: {labels_dir}")
    else:
        print("⚠️  No labels directory found - will only split images")
    
    # Shuffle images
    random.seed(seed)
    random.shuffle(images)
    
    # Calculate split indices
    total = len(images)
    train_end = int(total * train_ratio)
    valid_end = train_end + int(total * valid_ratio)
    
    splits = {
        'train': images[:train_end],
        'valid': images[train_end:valid_end],
        'test': images[valid_end:]
    }
    
    print(f"\n📊 Split breakdown:")
    print(f"   Train: {len(splits['train'])} images ({len(splits['train'])/total*100:.1f}%)")
    print(f"   Valid: {len(splits['valid'])} images ({len(splits['valid'])/total*100:.1f}%)")
    print(f"   Test:  {len(splits['test'])} images ({len(splits['test'])/total*100:.1f}%)")
    print()
    
    # Create output directories
    for split_name in ['train', 'valid', 'test']:
        (output_path / split_name / 'images').mkdir(parents=True, exist_ok=True)
        if has_labels:
            (output_path / split_name / 'labels').mkdir(parents=True, exist_ok=True)
    
    # Copy files
    print("📦 Copying files...")
    for split_name, image_list in splits.items():
        for img_file in image_list:
            # Copy image
            dest_img = output_path / split_name / 'images' / img_file.name
            shutil.copy2(img_file, dest_img)
            
            # Copy corresponding label if exists
            if has_labels:
                label_file = labels_dir / f"{img_file.stem}.txt"
                if label_file.exists():
                    dest_label = output_path / split_name / 'labels' / label_file.name
                    shutil.copy2(label_file, dest_label)
        
        print(f"   ✅ {split_name}: {len(image_list)} files copied")
    
    # Create data.yaml
    yaml_path = output_path / 'data.yaml'
    yaml_content = f"""# Dataset configuration for YOLO
# Auto-generated by split_dataset.py

# Paths (relative to this file)
train: train/images
val: valid/images
test: test/images

# Number of classes
nc: 1

# Class names
names: ['bat']
"""
    
    with open(yaml_path, 'w') as f:
        f.write(yaml_content)
    
    print(f"\n✅ Dataset split complete!")
    print(f"📁 Output directory: {output_path.absolute()}")
    print(f"📄 Configuration: {yaml_path.absolute()}")
    print(f"\n💡 Next steps:")
    print(f"   1. Review the split to ensure it's balanced")
    print(f"   2. If you have labels to add, export from Label Studio")
    print(f"   3. Run training: python scripts/train.py --data {yaml_path}")


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='Split YOLO dataset into train/valid/test sets')
    
    parser.add_argument('--source', type=str, required=True,
                        help='Source directory containing images (and optionally labels/)')
    parser.add_argument('--output', type=str, default='dataset',
                        help='Output directory for split dataset (default: dataset)')
    parser.add_argument('--train', type=float, default=0.7,
                        help='Training set ratio (default: 0.7)')
    parser.add_argument('--valid', type=float, default=0.15,
                        help='Validation set ratio (default: 0.15)')
    parser.add_argument('--test', type=float, default=0.15,
                        help='Test set ratio (default: 0.15)')
    parser.add_argument('--seed', type=int, default=42,
                        help='Random seed for reproducibility (default: 42)')
    
    args = parser.parse_args()
    
    split_dataset(
        source_dir=args.source,
        output_dir=args.output,
        train_ratio=args.train,
        valid_ratio=args.valid,
        test_ratio=args.test,
        seed=args.seed
    )
